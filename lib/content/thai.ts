const L = (
  id: string,
  glyph: string,
  text: string,
  latin: string,
  gloss: string,
  extra: Partial<Lexeme> = {},
): Lexeme => ({ id, glyph, text, latin, gloss, ...extra });

const P = (
  id: string,
  glyph: string,
  text: string,
  latin: string,
  gloss: string,
  tiles: string[],
  extraTiles: string[] = [],
): Phrase => ({ id, glyph, text, latin, gloss, tiles, extraTiles });

const map = <T extends { id: string }>(items: T[]): Record<string, T> =>
  Object.fromEntries(items.map((item) => [item.id, item])) as Record<string, T>;

